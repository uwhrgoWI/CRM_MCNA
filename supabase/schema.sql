-- ---------------------------------------------------------------------
-- Row Level Security: demo-grade open access for the anon key.
-- The app does its own role-based gating client-side; tighten these
-- policies before using with real customer data.
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'staff_users','companies','contacts','leads','deals','tasks',
    'activities','products','quotes','invoices','tickets',
    'audit_log','notifications','revenue_months'
  ] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "demo_full_access" on %I', t);
    execute format(
      'create policy "demo_full_access" on %I for all to anon, authenticated using (true) with check (true)', t
    );
  end loop;
end $$;
