-- =====================================================================
-- MCNA CRM VN - Supabase Schema
-- Mirrors the in-app data model (src/crm-database.js).
-- Column names are quoted camelCase so rows map 1:1 to the JS objects.
-- Each table has an `extra jsonb` catch-all for fields the app adds at
-- runtime, and a `seq` identity used only for stable ordering.
